/**
 * Pre-build step.
 *
 * The gallery clips are rendered by a separate job. This script finds the
 * rendered files anywhere in the repository, copies them into
 * site/public/clips/ and records which ones exist in
 * src/data/clip-manifest.json, so the page can show a real poster and a real
 * player when the file is there, and an explicit "not yet rendered" state when
 * it is not. It never invents a file.
 */
import { copyFileSync, existsSync, mkdirSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const siteDir = dirname(dirname(fileURLToPath(import.meta.url)));
const repoDir = dirname(siteDir);
const publicDir = join(siteDir, 'public');
const clipsDir = join(publicDir, 'clips');
const manifestPath = join(siteDir, 'src', 'data', 'clip-manifest.json');

const IDS = ['launch-title', 'kinetic-type', 'product-loop', 'footage-title'];
const SKIP_DIRS = new Set(['node_modules', '.git', 'dist', '.vite', '.mavis', 'coverage']);

function walk(dir, out = [], depth = 0) {
  if (depth > 6) return out;
  let entries = [];
  try {
    entries = readdirSync(dir, { withFileTypes: true });
  } catch {
    return out;
  }
  for (const entry of entries) {
    if (entry.isDirectory()) {
      if (SKIP_DIRS.has(entry.name)) continue;
      walk(join(dir, entry.name), out, depth + 1);
    } else if (entry.isFile()) {
      out.push(join(dir, entry.name));
    }
  }
  return out;
}

mkdirSync(clipsDir, { recursive: true });

const allFiles = walk(repoDir);
const found = {};

for (const id of IDS) {
  const entry = { video: false, poster: false, videoSrc: `/clips/${id}.mp4`, posterSrc: `/clips/${id}.jpg` };
  for (const file of allFiles) {
    const name = file.split('/').pop() ?? '';
    if (name === `${id}.mp4`) {
      const target = join(clipsDir, `${id}.mp4`);
      if (file !== target) copyFileSync(file, target);
      entry.video = true;
      entry.videoBytes = statSync(target).size;
    }
    if (name === `${id}.jpg`) {
      const target = join(clipsDir, `${id}.jpg`);
      if (file !== target) copyFileSync(file, target);
      entry.poster = true;
      entry.posterBytes = statSync(target).size;
    }
  }
  found[id] = entry;
}

const manifest = {
  note: 'Generated by scripts/sync-clips.mjs — records which rendered clip files exist. Never a placeholder.',
  clips: found,
};

writeFileSync(manifestPath, `${JSON.stringify(manifest, null, 2)}\n`);

const missing = IDS.filter((id) => !found[id].video);
console.log(
  `[sync-clips] ${IDS.length - missing.length}/${IDS.length} clips present in ${relative(repoDir, clipsDir)}`,
);
if (missing.length) {
  console.log(`[sync-clips] not rendered yet: ${missing.join(', ')}`);
}
if (!existsSync(manifestPath)) {
  console.error('[sync-clips] failed to write the manifest');
  process.exit(1);
}
